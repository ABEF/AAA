"""Generate the immutable artwork inventory from the reviewed visual catalogue.

The deterministic catalogue is a finite set of entries, never mint randomness.
Production selection consumes authenticated VRF draws without replacement.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'design/nft-metadata/palette-system-v1/packed-catalog.json'
TARGET = ROOT / 'src/libraries/ZZZArtwork.sol'
RARITIES = ('commun', 'rare', 'legendary')

def _unique_pairs(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError('Artwork catalogue contains a duplicate JSON key')
        result[key] = value
    return result

def _reject_constant(value):
    raise ValueError('Artwork catalogue contains a nonfinite JSON constant')

def _finite_float(value):
    number = float(value)
    if not math.isfinite(number):
        raise ValueError('Artwork catalogue contains a nonfinite JSON number')
    return number

def generate() -> str:
    raw = CATALOG.read_bytes()
    catalog = json.loads(raw, object_pairs_hook=_unique_pairs, parse_constant=_reject_constant,
                         parse_float=_finite_float)
    if len(catalog['paletteOrder']) != 58:
        raise ValueError('Artwork catalogue must contain exactly 58 palettes')
    if catalog['patternOrder'] != ['arcs', 'panels', 'orbits', 'ribs']:
        raise ValueError('Artwork catalogue pattern identity differs from the reviewed order')
    masks = []
    for entry in catalog['paletteOrder']:
        mask = entry['mask']
        # A zero mask has no primaryColor and must never enter generated code.
        if type(mask) is not int or not 1 <= mask <= 255:
            raise ValueError('Artwork palette mask must identify at least one color')
        masks.append(mask)
    masks = bytes(masks).hex()
    inventories = []
    for rarity, count in zip(RARITIES, (600, 300, 100)):
        codes = catalog['codes'][rarity]
        if not isinstance(codes, list) or any(type(code) is not int for code in codes):
            raise ValueError('Artwork codes must be exact integers')
        data = bytes.fromhex(catalog['hex'][rarity])
        if len(data) != 2 * count:
            raise ValueError('Artwork rarity inventory differs from its fixed supply')
        if hashlib.sha256(data).hexdigest() != catalog['sha256'][rarity]:
            raise ValueError('Artwork rarity inventory digest differs from the catalogue')
        if [int.from_bytes(data[i:i+2], 'big') for i in range(0,len(data),2)] != codes:
            raise ValueError('Artwork decoded inventory differs from the catalogue codes')
        if not all(0 <= code < 58 * 4 for code in codes):
            raise ValueError('Artwork code exceeds the reviewed palette and pattern inventory')
        inventories.append(f'    bytes private constant {rarity.upper()} = hex"{data.hex()}";')
    return '''// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;

/// @notice Immutable visual catalogue. Generated by scripts/generate-artwork-library.py.
/// @dev Packed catalogue SHA-256: ''' + hashlib.sha256(raw).hexdigest() + '''
/// Entries encode palette * 4 + pattern. Fixed entry order is not randomness;
/// the NFT consumes authenticated VRF words through per-rarity draws without
/// replacement. Color, palette and circuit pattern never change reward weights.
library ZZZArtwork {
    uint8 internal constant PALETTE_COUNT = 58;
    uint8 internal constant PATTERN_COUNT = 4;
    bytes private constant MASKS = hex"''' + masks + '''";
''' + '\n'.join(inventories) + '''

    function item(uint8 rarity, uint256 index) internal pure returns (uint8 palette, uint8 pattern) {
        bytes memory entries = rarity == 0 ? COMMUN : rarity == 1 ? RARE : LEGENDARY;
        uint256 offset = index * 2;
        uint16 code = (uint16(uint8(entries[offset])) << 8) | uint8(entries[offset + 1]);
        return (uint8(code / PATTERN_COUNT), uint8(code % PATTERN_COUNT));
    }

    function mask(uint8 palette) internal pure returns (uint8) { return uint8(MASKS[palette]); }

    function primaryColor(uint8 palette) internal pure returns (uint8 color) {
        uint8 colors = mask(palette);
        while ((colors & (uint8(1) << color)) == 0) ++color;
    }
}
'''

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = generate()
    if args.check:
        if TARGET.read_text(encoding='utf-8') != source:
            print('Artwork library is stale; regenerate and review its source change.')
            return 1
        print('Artwork library matches the complete immutable catalogue.')
    else:
        TARGET.write_text(source, encoding='utf-8', newline='\n')
        print('Generated immutable 1,000-entry artwork library.')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
