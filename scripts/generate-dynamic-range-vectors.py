"""Independent Decimal/rational CL fixtures; does not import Solidity math."""
from decimal import Decimal, getcontext, ROUND_FLOOR, ROUND_CEILING
from pathlib import Path
import json

getcontext().prec = 120
ROOT = Path(__file__).resolve().parents[1]
D = Decimal
Q = 2**96
rows = []
for d0, d1, reverse in [(18,18,False),(18,6,False),(6,18,True),(6,18,False)]:
    scale = D(10)**(d1-d0)
    lo, hi = ((D(1)/D('1.5'),D(2)) if reverse else (D('.5'),D('1.5')))
    lower = int(((lo*scale).ln()/D('1.0001').ln()/60).to_integral_value(rounding=ROUND_FLOOR))*60
    upper = int(((hi*scale).ln()/D('1.0001').ln()/60).to_integral_value(rounding=ROUND_FLOOR))*60+60
    # TickMath rounds sqrt encodings up; independently exponentiate the tick.
    a = int((D('1.0001')**(D(lower)/2)*Q).to_integral_value(rounding=ROUND_CEILING))
    b = int((D('1.0001')**(D(upper)/2)*Q).to_integral_value(rounding=ROUND_CEILING))
    for price in map(D,('0.4','0.5','0.75','1','1.25','1.4','1.49','1.5','1.6')):
        ratio = (1/price if reverse else price)*scale
        spot = int(ratio.sqrt()*Q)
        p = max(a,min(b,spot)); liquidity=10**18
        amount0=liquidity*Q*(b-p)//(b*p)
        amount1=liquidity*(p-a)//Q
        price0,price1=(D(1),price) if reverse else (price,D(1))
        v0=D(amount0)*price0/D(10)**d0;v1=D(amount1)*price1/D(10)**d1
        rows.append(dict(decimals0=d0,decimals1=d1,reverse=reverse,price=str(price),lower=lower,upper=upper,
                         spot=str(spot),amount0=str(amount0),amount1=str(amount1),
                         token0_weight_ppm=int(v0/(v0+v1)*1_000_000)))
out=ROOT/'test/helpers/DynamicRangeVectors.sol'
lines=['// SPDX-License-Identifier: MIT','pragma solidity 0.8.26;',
       '// Generated by scripts/generate-dynamic-range-vectors.py with Decimal precision 120.',
       '// Independent rational expectations, no TickMath/SqrtPriceMath calls.',
       'library DynamicRangeVectors {',
       'struct V { uint8 d0; uint8 d1; bool reverse; uint256 priceE8; int24 lower; int24 upper; uint160 spot; uint256 a0; uint256 a1; uint256 weight0; }',
       'function get(uint256 i) internal pure returns (V memory) {']
for i,r in enumerate(rows):
    vals=[r['decimals0'],r['decimals1'],str(r['reverse']).lower(),int(D(r['price'])*10**8),r['lower'],r['upper'],r['spot'],r['amount0'],r['amount1'],r['token0_weight_ppm']]
    lines.append(f'if (i == {i}) return V('+','.join(map(str,vals))+');')
lines+=['revert("vector index");','}','}']
out.write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
(ROOT/'reports/dynamic-liquidity/range-vectors.json').write_text(json.dumps(rows,indent=2)+'\n',encoding='utf-8',newline='\n')
print(f'Wrote {len(rows)} independent range vectors')
